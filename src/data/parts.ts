import type { PartDef, PartArt, SlotId } from '../core/types';

function art(geometry: string, material: PartArt['material'], scale = 1): PartArt {
  return {
    geometry,
    material,
    anchor: geometry.split('.')[0] as SlotId,
    offset: [0, 0, 0],
    rotation: [0, 0, 0],
    scale,
    mirrored: false,
  };
}

